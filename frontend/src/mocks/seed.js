// path: các bước pipeline sau khi nộp; lịch sử trạng thái được dựng lại tương ứng
const app = (id, jobId, candidateId, cvId, path, appliedDaysAgo, coverLetter = '') => {
  const statuses = ['applied', ...path]
  const recruiter = jobs.find((j) => j.id === jobId).recruiterId === 'u-rec-1' ? 'Trần Thị Bình' : 'Lê Hoàng Nam'
  const history = statuses.map((status, i) => ({
    id: `${id}-h${i}`,
    fromStatus: i ? statuses[i - 1] : null,
    toStatus: status,
    note: STEP_NOTES[status] ?? '',
    changedBy: i ? recruiter : users.find((u) => u.id === candidateId).fullName,
    createdAt: daysAgo(Math.max(appliedDaysAgo - 2 * i, 0)),
  }))
  return {
    id,
    jobId,
    candidateId,
    cvId,
    status: statuses.at(-1),
    appliedAt: daysAgo(appliedDaysAgo),
    statusChangedAt: history.at(-1).createdAt,
    coverLetter,
    rating: null,
    rejectionReason: path.includes('rejected') ? 'Kinh nghiệm chưa phù hợp với yêu cầu của vị trí.' : '',
    history,
    aiReview: null,
  }
}

